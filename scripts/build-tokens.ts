// Generates src/styles/tokens.css from the DESIGN.md front matter in the meta repo, so the
// design source of truth stays in one place (tech design §1 "设计"). Run: npm run tokens
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const designPath = resolve(
	packageRoot,
	'../../company-os/06-app-development/design-system/DESIGN.md',
);
const outputPath = resolve(packageRoot, 'src/styles/tokens.css');

type TokenMap = Record<string, unknown>;

interface TypeStyle {
	size: string;
	weight: number;
	'line-height': number;
	'letter-spacing': string | number;
}

function readFrontMatter(path: string): TokenMap {
	const text = readFileSync(path, 'utf8').replace(/\r\n/g, '\n');
	const match = /^---\n([\s\S]*?)\n---\n/.exec(text);
	if (!match?.[1]) {
		throw new Error(`No YAML front matter found in ${path}`);
	}
	return parse(match[1]) as TokenMap;
}

function section(tokens: TokenMap, name: string): TokenMap {
	const value = tokens[name];
	if (typeof value !== 'object' || value === null) {
		throw new Error(`DESIGN.md front matter has no "${name}" section`);
	}
	return value as TokenMap;
}

function cssValue(value: unknown): string {
	return typeof value === 'number' && value === 0 ? '0' : String(value);
}

function simpleTokens(tokens: TokenMap, prefix: string): string[] {
	return Object.entries(tokens).map(
		([name, value]) => `--ck-${prefix}-${name}: ${cssValue(value)};`,
	);
}

function isTypeStyle(value: unknown): value is TypeStyle {
	return typeof value === 'object' && value !== null && 'size' in value;
}

function typographyTokens(typography: TokenMap): string[] {
	const lines: string[] = [];
	for (const [name, value] of Object.entries(typography)) {
		if (typeof value === 'string') {
			lines.push(`--ck-${name}: ${value};`);
			continue;
		}
		if (!isTypeStyle(value)) {
			throw new Error(`Unexpected typography token "${name}"`);
		}
		const letterSpacing = value['letter-spacing'];
		lines.push(
			`--ck-type-${name}-size: ${value.size};`,
			`--ck-type-${name}-weight: ${value.weight};`,
			`--ck-type-${name}-line-height: ${value['line-height']};`,
			`--ck-type-${name}-letter-spacing: ${letterSpacing === 0 ? '0' : letterSpacing};`,
		);
	}
	return lines;
}

// Shadows become variables; "frosted" is a pair of declarations, split into one variable each.
function elevationTokens(elevation: TokenMap): string[] {
	const lines: string[] = [];
	for (const [name, value] of Object.entries(elevation)) {
		const text = String(value);
		if (!text.includes(':')) {
			lines.push(`--ck-shadow-${name}: ${text};`);
			continue;
		}
		for (const declaration of text.split(';')) {
			const [property, ...rest] = declaration.split(':');
			if (property?.trim() && rest.length > 0) {
				lines.push(`--ck-${name}-${property.trim()}: ${rest.join(':').trim()};`);
			}
		}
	}
	return lines;
}

// Only machine-usable motion values; "reduce-motion" is prose guidance, not a token.
function motionTokens(motion: TokenMap): string[] {
	const lines = Object.entries(motion)
		.filter(([name]) => name.startsWith('duration-'))
		.map(([name, value]) => `--ck-motion-${name}: ${String(value)};`);
	const press = /transform:\s*(.+)$/.exec(String(motion.press ?? ''));
	if (press?.[1]) {
		lines.push(`--ck-motion-press-transform: ${press[1].trim()};`);
	}
	return lines;
}

function buildCss(tokens: TokenMap): string {
	const groups: [string, string[]][] = [
		['Colours', simpleTokens(section(tokens, 'colors'), 'color')],
		['Typography', typographyTokens(section(tokens, 'typography'))],
		['Spacing', simpleTokens(section(tokens, 'spacing'), 'space')],
		['Sizes', simpleTokens(section(tokens, 'size'), 'size')],
		['Radius', simpleTokens(section(tokens, 'rounded'), 'radius')],
		['Elevation', elevationTokens(section(tokens, 'elevation'))],
		['Motion', motionTokens(section(tokens, 'motion'))],
	];
	const body = groups
		.map(([title, lines]) =>
			[`\t/* ${title} */`, ...lines.map((line) => `\t${line}`)].join('\n'),
		)
		.join('\n\n');
	return [
		`/* GENERATED by scripts/build-tokens.ts from DESIGN.md v${String(tokens.version)} — do not edit; run npm run tokens */`,
		':root {',
		body,
		'}',
		'',
	].join('\n');
}

writeFileSync(outputPath, buildCss(readFrontMatter(designPath)), 'utf8');
console.log(`Wrote ${outputPath}`);
